import { DEFAULT_LOCALE, localizedPath, type SupportedLocale } from "../i18nRouting";

/**
 * Builds the `_redirects` file that sends a locale-free URL (`/blog/foo`) to
 * its default-locale page (`/en/blog/foo`).
 *
 * Every page lives under a locale segment, but links from before the locale
 * moved into the path still point at the bare form. The SPA's LocaleRedirect
 * catches those once JavaScript runs; this file answers them with a real 302
 * first, which is what a crawler that never runs the app needs.
 *
 * Cloudflare's `_redirects` cannot say "every path that does not start with
 * /en or /pt": its rules fire even when a file matches, so a catch-all
 * `/* /en/:splat` would loop on the localized pages themselves. Listing each
 * page explicitly avoids that, and a URL that matches no page falls through to
 * the 404 page instead of being redirected to a localized 404.
 *
 * Imported by a Node script as well as by the app, so: no `import.meta`, no
 * `process`, no React.
 */

/** Cloudflare reads at most this many static rules from `_redirects`. */
export const MAX_STATIC_REDIRECTS = 2000;

export function buildLocaleRedirects(
  pagePaths: readonly string[],
  locale: SupportedLocale = DEFAULT_LOCALE,
): string {
  const prefix = `/${locale}/`;

  const lines = [...new Set(pagePaths)]
    .filter((path) => path.startsWith(prefix))
    .map((path) => path.slice(prefix.length - 1))
    // `*` and `:` mean splat and placeholder in a rule's source, so a topic key
    // holding one would turn its line into a pattern. Such a page keeps only
    // the client-side redirect.
    .filter((bare) => !/[*:\s]/.test(bare))
    .sort()
    .map((bare) => `${bare} ${localizedPath(locale, bare)} 302`);

  if (lines.length > MAX_STATIC_REDIRECTS) {
    throw new Error(
      `${lines.length} locale redirects exceed Cloudflare's limit of ${MAX_STATIC_REDIRECTS} ` +
        "static rules in _redirects. The extra lines would be dropped without a warning.",
    );
  }

  return [
    "# Generated by scripts/prerender.mts. Do not edit by hand.",
    "# Each locale-free page URL goes to its default-locale page.",
    ...lines,
    "",
  ].join("\n");
}
